// Builds vendor/words.js from SCOWL (npm package wordlist-english): level 10 holds the most common English words,
// level 20 the next most common. Words in neither list (names, invented terms, rare words) get a little more time.
const fs = require('fs');
const path = require('path');

const list = level => require(`wordlist-english/english-words-${level}.json`).map(w => w.toLowerCase());
// Common words SCOWL leaves out of these levels (it lists them elsewhere, e.g. as abbreviations).
const extra = ['i', 'mr', 'mrs', 'ms', 'dr', 'ok'];
const common = [...new Set([...list(10), ...extra])];
const known = list(20).filter(w => !common.includes(w));

const out = path.join(__dirname, '..', 'vendor');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'words.js'), `// Generated by tools/words.js from SCOWL via wordlist-english (see words.LICENSE.txt). Do not edit.
var novelRsvpWords = { common: ${JSON.stringify(common.join(' '))}, known: ${JSON.stringify(known.join(' '))} };
`);
fs.copyFileSync(require.resolve('wordlist-english/Copyright'), path.join(out, 'words.LICENSE.txt'));
console.log(`vendor/words.js: ${common.length} common, ${known.length} known words`);
